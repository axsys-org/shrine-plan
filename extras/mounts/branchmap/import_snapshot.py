#!/usr/bin/env python3
"""Compile a public observation snapshot into Foil literals; no ledger logic."""
import hashlib,json,unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parent
DATA=ROOT.parents[1]/'experiments/branchmap/data'
def quote(s):
    # ASCII is the current prepared-text contract. Full originals remain in data/.
    return '"'+s.encode('ascii','backslashreplace').decode().replace('"','""').replace('\n',' ')+'"'
def display(s):
    # Presentation labels are ASCII; the raw snapshot retains original spelling.
    return unicodedata.normalize("NFKD",s).encode("ascii","ignore").decode().strip()
def generate():
    sample=json.loads((DATA/'sample.json').read_text())
    rows=[]
    for source in sample:
        m=source['market']
        if m['outcomeType']=='BINARY':
            names=['YES','NO']; prices=[round(m['probability']*1000000),round((1-m['probability'])*1000000)]
        else:
            assert m['shouldAnswersSumToOne']
            names=[a['text'] for a in m['answers']];prices=[round(a['probability']*1000000) for a in m['answers']]
        provenance=json.dumps({'source':source['source_api'],'fetched_at':source['fetched_at'],'raw_sha256':source['raw_sha256'],'rules':m.get('textDescription',m.get('description','')),'source_is_resolved':m.get('isResolved',False)},ensure_ascii=True,separators=(',',':'))
        raw=DATA/'raw'/f"{m['id']}.json"
        assert hashlib.sha256(raw.read_bytes()).hexdigest()==source['raw_sha256']
        rows.append('      (branchmap/market '+quote(m['id'])+' '+quote(display(m['question']))+' ['+' '.join(map(lambda name: quote(display(name)),names))+'] ['+' '.join(map(str,prices))+'] 0 '+quote(provenance)+')')
    return '- branchmap_domain\n\n\' Generated by import_snapshot.py; resolution=0 is a local simulation, not venue status.\n+ branchmap_sample\n  + markets\n    ^ row[branchmap/market]\n    [\n'+'\n'.join(rows)+'\n    ]\n  + initial\n    ^ branchmap/book\n    | branchmap/initial branchmap_sample/markets\n'
if __name__=='__main__':
    (ROOT/'sample.foil').write_text(generate())
