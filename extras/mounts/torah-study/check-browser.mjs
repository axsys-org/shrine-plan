// Run against a disposable world: this intentionally leaves a published fork.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
const [base,mash,out='/tmp/torah-study-check']=process.argv.slice(2);
if(!base||!mash)throw Error('Usage: check-browser.mjs URL MASH_ROOT [OUTPUT]');
const {chromium}=createRequire(resolve(mash,'tests/integration/package.json'))('@playwright/test');
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1280,height:960}});
page.setDefaultTimeout(90000);
const errors=[],puts=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(new URL(r.url()).pathname==='/goo/act')puts.push(r);});
const button=name=>page.getByRole('button',{name,exact:true});
const slot=name=>page.locator('input[data-input-slot$="/'+name+'"]');
const ledger=async()=>await (await page.request.get(base+'/torah-study/leaves')).json();
await mkdir(out,{recursive:true});
try {
  assert.equal((await page.goto(base+'/torah-study')).status(),200);
  const before=await ledger(), id='D'+(before.distinctions.length+1), edition='R'+(before.leaves.length+1);
  assert.equal(before.draft,null,'Start with no unpublished fork');
  await button('Compare readings').click();
  assert.equal(await slot('distinction').inputValue(),before.distinctions.at(-1)?.id ?? '');
  for (const column of await page.locator('.daf > .margin').all()) {
    const premise=await column.locator('p').innerText();
    await page.locator('.table').getByText(premise,{exact:true}).waitFor();
  }
  await button('Return to study table').click();
  await button('Introduce a distinction').waitFor();
  const phrase=page.getByRole('button',{name:'יאוש שלא מדעת'});
  await phrase.click();
  await page.getByText('Open the kushya',{exact:true}).click();
  assert.equal(await phrase.getAttribute('aria-pressed'),'true');
  assert(await page.getByText('Can a finder rely on',{exact:false}).isVisible());
  assert.equal(puts.length,0,'Reading evidence never mutates the record');
  await page.screenshot({path:resolve(out,'folio.png'),fullPage:true});
  await button('Introduce a distinction').click();
  await slot('name').fill('ידיעה / Actual notice versus predictable loss');
  await slot('consequence').fill('An unmarked coin was found before the owner noticed.');
  await slot('limit').fill('A marked vessel still offers a route to recovery.');
  await button('Record distinction').click();
  await button('Fork Rava').waitFor();
  await page.locator('#leaf-'+id).waitFor();
  const d=(await ledger()).distinctions.at(-1);
  assert.equal(d.lemma,await phrase.getAttribute('id'));
  assert.equal(await slot('distinction').inputValue(),id,'The form suggests the actual saved distinction');
  await button('Fork Rava').click();
  await button('Publish alternative').waitFor();
  let book=await ledger();
  assert.equal(book.draft.distinction,id);
  assert.equal(book.draft.parent,'B');
  assert.equal(book.draft.parentName,'Rava');
  assert.equal(await page.locator('.margin').last().locator('a').getAttribute('href'),book.draft.sourceUrl);
  await page.locator('#leaves').getByRole('heading',{name:'From '+book.draft.parentName}).waitFor();
  assert.equal(book.evidence.id,d.lemma);
  await page.reload();
  await button('Resume a fork').click();
  assert.equal(await slot('draft_id').inputValue(),edition);
  const thesis='A predictable response is evidence about the owner, not proof of notice.';
  await slot('thesis').fill(thesis);
  await button('Publish alternative').click();
  await button('Introduce a distinction').waitFor();
  await page.reload();
  await page.locator('#leaves').getByText(thesis,{exact:true}).waitFor();
  const saved=await ledger();
  assert.equal(saved.draft,null);
  assert.deepEqual(saved.leaves.at(-1),{...book.draft,thesis});
  assert.deepEqual(saved.leaves.slice(0,-1),before.leaves);
  assert.equal(puts.length,3);
  await page.screenshot({path:resolve(out,'published.png'),fullPage:true});
  await page.setViewportSize({width:390,height:840});
  await button('Introduce a distinction').waitFor();
  await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth+1);
  assert.deepEqual(errors,[]);
  console.log('PASS: exact lemma, kushya, bilingual distinction, fork, resume, publish, persisted reread, 3 Goo invocations, narrow folio.');
} catch(e) {
  console.error(await page.locator('body').innerText());
  await page.screenshot({path:resolve(out,'failure.png'),fullPage:true});
  throw e;
} finally {await browser.close();}
