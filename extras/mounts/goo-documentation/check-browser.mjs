// Real installed namespace and render responses; no mocked documentation data.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {mkdir,writeFile} from 'node:fs/promises';
const [base,mash,out='/tmp/goo-documentation-browser']=process.argv.slice(2);
if(!base||!mash)throw Error('Usage: check-browser.mjs URL MASH_ROOT [OUTPUT]');
const engines=createRequire(resolve(mash,'tests/integration/package.json'))('@playwright/test');
await mkdir(out,{recursive:true});const results=[];
for(const name of (process.env.BROWSERS||'chromium,firefox,webkit').split(',')) {
 const browser=await engines[name].launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1050}});page.setDefaultTimeout(45000);
 const errors=[],writes=[],sources=[],checks=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('request',r=>{const path=new URL(r.url()).pathname;if(path==='/goo/act'||path.startsWith('/grove/dev/'))writes.push(path);if(path==='/goo/source')sources.push(new URL(r.url()));});
 const article=path=>page.locator(`.goo-documentation[data-subject="${path}"]`);
 const member=path=>page.locator(`wa-tree-item[subject="${path}"]`);
 const check=text=>{checks.push(text);console.log(name,text);};
 try {
  const response=await page.goto(base+'/goo-documentation');
  assert.equal(response.status(),200);assert((await response.text()).includes('data-workspace'));
  await article('/0x11/lib/pact/lore').waitFor();
  assert((await article('/0x11/lib/pact/lore').innerText()).includes('Structured documentation'));
  assert((await article('/0x11/lib/pact/lore').locator('.doc-signature').innerText()).includes('/0x11/lib/pact/lore@x1['));
  const contextPath=await page.locator('#workspace').getAttribute('data-target');
  assert.match(contextPath,/^\/0x11\/goo\/ses\/[0-9]+$/);
  const contextValue=await page.request.post(base+'/goo/render',{form:{target:contextPath,slot:'/sys/slot/synthetic',width:'800',textScale:'1',direction:'ltr'}});
  assert.equal(contextValue.status(),200);
  const stored=await contextValue.json();
  assert(stored.html.includes('source_path'));
  assert(stored.html.includes('/0x11/lib/pact/lore'));
  check('workspace receiver is an inspectable namespace context with a numeric session ID');
  check('real Grove workspace resolves its initial namespace selection');
  await member('/0x11/lib/pact/lore/line').press('Enter');
  await article('/0x11/lib/pact/lore/line').waitFor();
  await member('/0x11/lib/pact/lore').press('Enter');
  await article('/0x11/lib/pact/lore').waitFor();
  assert((await article('/0x11/lib/pact/lore').innerText()).includes('Structured documentation'));
  await page.getByRole('tab',{name:'Values',exact:true}).click();
  await page.locator('.goo-pane:not([hidden]) .goo-follow .goo-surface').waitFor();
  await page.getByRole('tab',{name:'Documentation',exact:true}).click();
  await article('/0x11/lib/pact/lore').waitFor();
  check('keyboard selection reads published lore; Values and Documentation share selection');
  await page.goto(base+'/goo-documentation?path=%2F0x11%2Flib%2Fpact');
  await member('/0x11/lib/pact/lore').waitFor();
  assert.equal(await member('/0x11/lib/pact/lore/put').count(),0);
  await member('/0x11/lib/pact/lore').press('ArrowRight');
  await member('/0x11/lib/pact/lore/put').waitFor();
  assert(sources.some(url=>url.searchParams.get('parent')==='/0x11/lib/pact/lore'));
  await member('/0x11/lib/pact/lore/put').press('Enter');
  await article('/0x11/lib/pact/lore/put').waitFor();
  await article('/0x11/lib/pact/lore/put').locator('summary').filter({hasText:/source/i}).click();
  await article('/0x11/lib/pact/lore/put').locator('.doc-source pre').waitFor({state:'visible'});
  const source=await article('/0x11/lib/pact/lore/put').locator('.doc-source pre').innerText();
  assert(source.includes('tale'));assert(!source.includes('One-line lore'));
  check('branch expansion fetches children lazily and shows actual source');
  await page.locator('.goo-navigate input').fill('/0x11/lib/pact/lore/line');
  await page.getByRole('button',{name:'Go to path',exact:true}).click();
  await article('/0x11/lib/pact/lore/line').waitFor();
  assert(new URL(page.url()).searchParams.get('path')==='/0x11/lib/pact/lore/line');
  await page.reload();await article('/0x11/lib/pact/lore/line').waitFor();
  await page.goBack();await member('/0x11/lib/pact/lore').waitFor();
  check('path form, reload, and browser Back restore the browsing root');
  await page.getByRole('navigation',{name:'Namespace roots'}).getByRole('link',{name:'Library',exact:true}).click();
  await member('/0x11/lib').waitFor();
  await page.locator('.goo-tree-notice').filter({hasText:'raw keys'}).waitFor();
  const more=page.getByRole('button',{name:'Load more children of /0x11/lib',exact:true});
  await more.waitFor();
  const count=await page.locator('wa-tree-item').count();await more.click();
  await page.waitForFunction(count=>document.querySelectorAll('wa-tree-item').length>count,count);
  assert(sources.some(url=>url.searchParams.get('parent')==='/0x11/lib'&&url.searchParams.get('after')?.startsWith('v1/')));
  check('large namespace roots page with opaque cursors and disclose omitted raw keys');
  await page.goto(base+'/goo-documentation?path=%2F0x11%2Flib%2Fpact%2Flore');
  await article('/0x11/lib/pact/lore').waitFor();
  await page.setViewportSize({width:760,height:1000});
  await article('/0x11/lib/pact/lore').waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  check('narrow layout keeps navigation and reading content within the viewport');
  await page.screenshot({path:resolve(out,name+'-narrow.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1050});
  await page.screenshot({path:resolve(out,name+'.png'),fullPage:true});
  assert.deepEqual(writes,[]);assert.deepEqual(errors,[]);
  check('browsing sends no domain actions and produces no uncaught browser errors');
  results.push({engine:name,version:browser.version(),checks});
 } catch(error) {await page.screenshot({path:resolve(out,name+'-failure.png'),fullPage:true});results.push({engine:name,version:browser.version(),checks,error:String(error),errors});console.error(await page.locator('body').innerText());throw error;}
 finally {await writeFile(resolve(out,'results.json'),JSON.stringify(results,null,2)+'\n');await browser.close();}
}
