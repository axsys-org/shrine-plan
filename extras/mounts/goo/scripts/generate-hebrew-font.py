"""Build the bounded ASCII + unpointed Hebrew run face (fonttools 4.66)."""
import hashlib, json, sys
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
font = TTFont(source, recalcTimestamp=False)
license = font['name'].getDebugName(13)
assert license and 'Bitstream' in license
(root/'run-fonts'/'Hebrew-LICENSE.txt').write_text(license+'\n')
chars = [*range(32,127),*range(0x5d0,0x5eb)]
sub = subset.Subsetter()
sub.populate(unicodes=chars)
sub.subset(font)
out = root.parent/'explorer'/'goo-hebrew.ttf'
font.save(out)
cmap = font.getBestCmap()
widths = [font['hmtx'][cmap[c]][0] for c in chars]
digest = hashlib.sha256(out.read_bytes()).hexdigest()
asc, desc = font['hhea'].ascent, -font['hhea'].descent
data = {'family':'Goo Hebrew','weight':400,'style':'normal','fontSHA256':digest,'unitsPerEm':font['head'].unitsPerEm}
(root/'run-fonts'/'hebrew.json').write_text(json.dumps(data,indent=2)+'\n')
(root/'hebrew_font.foil').write_text(f"""- goo_app/run_fonts

' Generated by scripts/generate-hebrew-font.py. U+0020..007E followed by U+05D0..05EA.
+ goo_hebrew_font
  + face
    ^ goo_run_fonts/font
    | goo_run_fonts/font "hebrew" "Goo Hebrew" (goo_fonts/info "hebrew" "DejaVuSans.ttf" "{hashlib.sha256(source.read_bytes()).hexdigest()}" "{digest}" 400 {font['head'].unitsPerEm} .false [{' '.join(map(str,widths))}]) {asc} {desc}
""")
