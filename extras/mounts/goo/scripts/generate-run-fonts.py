#!/usr/bin/env python3
"""Generate the run-style font extension from vendored sources (fonttools 4.66.0)."""
import hashlib, io, json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset
root = Path(__file__).resolve().parents[1]
out = root / "run-fonts"
out.mkdir(exist_ok=True)
fonts = {}
pinned = {f["source"]: f["sourceSHA256"] for f in json.loads((root / "profile/metrics.json").read_text()).values()}
for name, source, family, weight, italic in [
    ("italic520", "Inter-Italic.ttf", "Goo Sans", 520, True),
    ("italic550", "Inter-Italic.ttf", "Goo Sans", 550, True),
    ("italic620", "Inter-Italic.ttf", "Goo Sans", 620, True),
    ("italic650", "Inter-Italic.ttf", "Goo Sans", 650, True),
    ("italic750", "Inter-Italic.ttf", "Goo Sans", 750, True),
    ("mono700", "RobotoMono.ttf", "Goo Mono", 700, False),
]:
    data = root / "fonts" / source
    assert hashlib.sha256(data.read_bytes()).hexdigest() == pinned[source], "Unpinned source font"
    font = TTFont(data, recalcTimestamp=False)
    axes = {a.axisTag: (weight if a.axisTag == "wght" else 14 if a.axisTag == "opsz" else a.defaultValue) for a in font["fvar"].axes}
    font = instantiateVariableFont(font, axes, inplace=True)
    options = subset.Options()
    options.layout_features = []
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=range(32, 127))
    sub.subset(font)
    font.recalcTimestamp = False
    file = out / ("goo-" + name + ".ttf")
    font.save(file)
    cmap = font.getBestCmap()
    fonts[name] = dict(file=file.name, family=family, weight=weight, style="italic" if italic else "normal",
        source=source, sourceSHA256=hashlib.sha256(data.read_bytes()).hexdigest(),
        fontSHA256=hashlib.sha256(file.read_bytes()).hexdigest(), unitsPerEm=font["head"].unitsPerEm,
        ascent=font["hhea"].ascent, descent=-font["hhea"].descent,
        advances=[font["hmtx"].metrics[cmap[c]][0] for c in range(32,127)])
(out / "fonts.json").write_text(json.dumps(dict(version=1, fonts=fonts), indent=2)+"\n")
s = "- goo_app/profile\n\n' Generated by scripts/generate-run-fonts.py. Separate pinned run-style extension.\n+ goo_run_fonts\n  + font\n    : id=str family=str info=goo_fonts/info ascent=nat descent=nat\n  + base\n    \\ face=goo_fonts/face\n    ^ goo_run_fonts/font\n    | goo_run_fonts/font (goo_profile/font_id face) (goo_profile/font_family face) (goo_fonts/metadata face) (goo_profile/font_ascent face) (goo_profile/font_descent face)\n"
for name, f in fonts.items():
    args = " ".join(json.dumps(f[k]) for k in ["source","sourceSHA256","fontSHA256"])
    s += f'  + {name}\n    ^ goo_run_fonts/font\n    | goo_run_fonts/font "{name}" "{f["family"]}" (goo_fonts/info "{name}" {args} {f["weight"]} {f["unitsPerEm"]} .{"true" if f["style"]=="italic" else "false"} [' + " ".join(map(str,f["advances"])) + f']) {f["ascent"]} {f["descent"]}\n'
(root / "run_fonts.foil").write_text(s)
