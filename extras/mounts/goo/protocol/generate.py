#!/usr/bin/env python3
"""Generate typed Foil records/BAT writers and borrowed Rust field descriptors.
Only the deliberately small proto2 subset in goo.proto is supported; protoc
validates the independent schema. JSON adapters exist for legacy domain APIs.
"""
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parent
text=re.sub(r'//[^\n]*','', (ROOT/'goo.proto').read_text())
messages={}
for name,body in re.findall(r'message\s+(\w+)\s*\{((?:[^{}]|\{[^{}]*\})*)\}',text):
    fields=re.findall(r'(?:(required|optional|repeated)\s+)?(\w+)\s+(\w+)\s*=\s*(\d+)\s*;',body)
    messages[name]=[(mode or 'optional',typ,key,int(tag)) for mode,typ,key,tag in fields]
assert len(messages)>40
snake=lambda s: re.sub(r'(?<!^)(?=[A-Z])','_',s).lower()
scalar={'string':'str','bool':'bool','uint32':'nat','uint64':'nat','double':'nat'}
base=lambda t:scalar.get(t,'goo_wire/'+snake(t))
ftype=lambda m,t: 'row['+base(t)+']' if m=='repeated' else ('maybe['+base(t)+']' if m=='optional' else base(t))
wrappers={'TextRuns','RunFragments','Description'}
lines=['- wire_proto','- goo_app/numbers',"", "' GENERATED by protocol/generate.py. Do not edit.",'+ goo_wire']
lines += ['  + optional', '    (@@ a)', '    \\ write={\\ a}any value=maybe[a]', '    ^ any', '    ? value', '     > ./none (bat_bytes 0 0)', '     > (./some item) (write item)', '  + map_optional', '    (@@ a b)', '    \\ f={\\ a}b value=maybe[a]', '    ^ maybe[b]', '    < item value', '    | ./some (f item)']
# Helpers for legacy domain objects, never a wire-level arbitrary value type.
lines+=['  + field','    \\ key=str value=json','    ^ json','    ?> (json/obj fields) value jnull','    | (goo_text/field fields key).fall(jnull)',
'  + string','    \\ value=json','    ^ maybe[str]','    ?> (json/str text) value .none','    | ./some text',
'  + boolean','    \\ value=json','    ^ maybe[bool]','    ?> (json/boo value) value .none','    | ./some value',
'  + natural','    \\ value=json','    ^ maybe[nat]','    ?> (json/num negative value) value .none','    ? negative .none','    ? (gt value 18446744073709551615) .none','    | ./some value',
'  + double','    \\ value=json','    ^ maybe[nat]','    < value (goo_number/decode value)','    | ./some value.bits',
'  + array','    \\ value=json','    ^ maybe[row[json]]','    ? (equal value jnull) (./some [])','    ?> (json/arr values) value .none','    | ./some values']
parse={'string':'goo_wire/string','bool':'goo_wire/boolean','uint32':'goo_wire/natural','uint64':'goo_wire/natural','double':'goo_wire/double'}
for name,fs in messages.items():
    if name=='Response':continue
    n=snake(name)
    lines+=['  + '+n,'    : '+' '.join(snake(k)+'='+ftype(m,t) for m,t,k,tag in fs)]
    lines+=['  + '+n+'_bytes','    \\ value=goo_wire/'+n,'    ^ any','    | bat_concat [']
    for mode,t,key,tag in fs:
        k=snake(key)
        def enc(v):
            if t=='string':return f'(wire_proto/text {tag} {v})'
            if t=='bool':return f'(wire_proto/number {tag} (? {v} 1 0))'
            if t=='double':return f'(wire_proto/fixed64 {tag} {v})'
            if t in scalar:return f'(wire_proto/number {tag} {v})'
            return f'(wire_proto/message {tag} (goo_wire/{snake(t)}_bytes {v}))'
        if mode=='required': expr=enc('value.'+k)
        elif mode=='optional':expr=f'(goo_wire/optional[{base(t)}] (\\ item {enc("item")}) value.{k})'
        else:expr=f'(bat_concat (value.{k}.map((\\ item {enc("item")}))))'
        lines+=['        '+expr]
    lines+=['      ]']
    if name in ['Myth','Pail']:continue
    lines+=['  + '+n+'_from_json','    \\ document=json','    ^ maybe[goo_wire/'+n+']']
    if name=='Pane':lines+=['    ? (equal (goo_wire/field "kind" document) (json/str "patch")) .none']
    if name in wrappers:lines+=['    = document (json/obj [(jkv "values" document)])']
    for mode,t,key,tag in fs:
        k=snake(key); func=parse.get(t,'goo_wire/'+snake(t)+'_from_json'); raw=f'(goo_wire/field "{key}" document)'
        if mode=='required':lines+=['    < '+k+f' ({func} {raw})']
        elif mode=='optional':lines+=['    = '+k+'=maybe[maybe['+base(t)+']]', f'        ? (equal {raw} jnull) (./some .none)', f'        < held ({func} {raw})','        | ./some (./some held)','    < '+k+' '+k]
        else:lines+=['    = '+k+'=maybe[row['+base(t)+']]', f'        < values (goo_wire/array {raw})',f'        < items (values.stream.traverse_maybe({func}))','        | ./some items.row','    < '+k+' '+k]
    lines+=['    | ./some (goo_wire/'+n+' '+' '.join(snake(k) for _,_,k,_ in fs)+')']
(ROOT.parent/'wire.foil').write_text('\n'.join(lines)+'\n'+(ROOT/'pail_adapter.foil.inc').read_text())
# Rust descriptors are interpreted by a serde Deserializer into existing typed
# models. Unlike serde_json::Value this does not allocate a second response tree.
r=['// Generated from goo.proto by protocol/generate.py.','use super::{Field, Kind, Mode, Schema};']
for name,fs in messages.items():
    entries=[]
    for mode,t,key,tag in fs:
        kind={'string':'Kind::String','bool':'Kind::Bool','uint32':'Kind::U32','uint64':'Kind::U64','double':'Kind::Double'}.get(t,'Kind::Message(&'+t.upper()+')')
        entries.append(f'Field {{ name: "{key}", tag: {tag}, kind: {kind}, mode: Mode::{mode.title()} }}')
    r+=[f'pub static {name.upper()}: Schema = Schema {{ name: "{name}", fields: &[',*['    '+e+',' for e in entries],'] };']
(ROOT/'wire_schema.rs').write_text('\n'.join(r)+'\n')
print('Generated',len(messages),'domain messages')
